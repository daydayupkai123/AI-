def _report(*pages: str) -> list[Material]:
    return [Material(sig="x", filename="评审文件.pdf", role="review_report",
                     doc={"pages": [{"no": i + 12, "text": t} for i, t in enumerate(pages)]})]


def test_line_ocr_and_merged_blocks_agree():
    for p12 in (P12_LINES, P12_MERGED):
        got = review_quotes(_report(p12, P15), SUP)
        assert {s: v["value"] for s, v in got.items()} == WANT
        assert {v["page"] for v in got.values()} == {13}  # 取自排名表页，不取列式表头页


def test_amounts_from_same_line_are_discarded():
    # 一行里列出三家名称和三个金额（无法确定对应关系）→ 不取，宁可识别不出
    text = "供应商 济宁鼎丞劳务有限公司 / 济宁华擎工程管理有限公司\n含税报价 300000.00 310000.00\n山东泽陆园工程建设有限公司"
    got = review_quotes(_report(text), SUP)
    assert "济宁鼎丞劳务有限公司" not in got and "济宁华擎工程管理有限公司" not in got


def test_identical_quotes_on_different_rows_are_kept():
    text = "评审意见 报价\n济宁鼎丞劳务有限公司 300000.00\n济宁华擎工程管理有限公司 300000.00\n山东泽陆园工程建设有限公司 310000.00"
    got = review_quotes(_report(text), SUP)
    assert {s: v["value"] for s, v in got.items()} == {
        "济宁鼎丞劳务有限公司": 300000.0, "济宁华擎工程管理有限公司": 300000.0, "山东泽陆园工程建设有限公司": 310000.0}
